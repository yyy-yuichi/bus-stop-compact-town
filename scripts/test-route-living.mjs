assert.equal(facilities.find(f=>f.id==='osm-node-4354872989').properties.name,'イオン光店');
for(const id of ['osm-way-354319153','osm-node-1423657276'])assert.equal(facilities.find(f=>f.id===id).properties.category,'reference');
