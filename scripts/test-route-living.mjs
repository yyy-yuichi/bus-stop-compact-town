import assert from 'node:assert/strict';
import fs from 'node:fs';
import { activeTrips, validStudyDate, shoppingPlans, serviceDate, timeMinutes, studyFreshness } from '../src/routeLiving.ts';
const data = JSON.parse(fs.readFileSync('public/data/route-living-pilot.json','utf8'));
const pdf = JSON.parse(fs.readFileSync('data-sources/route-living-pilot-20260914/gururin-pdf-check.json','utf8'));
assert.equal(serviceDate('2026-02-30'),null);
assert.equal(serviceDate('2026-09-15'),'20260915');
assert.equal(validStudyDate(data,'2027-04-01'),false);
assert.equal(activeTrips(data,'2027-04-01').length,0);
assert.equal(activeTrips(data,'2026-09-15').length,6);
assert.equal(activeTrips(data,'2026-09-19').length,5);
assert.equal(activeTrips(data,'2026-09-21').length,5,'Monday public-holiday exception overrides weekdays');
assert.equal(activeTrips(data,'2026-12-29').length,4,'Official year-end exception excludes the marked morning and afternoon trips');
assert.equal(activeTrips(data,'2027-01-03').length,4);
assert.equal(activeTrips(data,'2027-01-04').length,6);
const special=structuredClone(data);
special.calendar=[];special.exceptions=[{date:'20260915',service_id:'毎日',exception_type:'1'}];
assert.equal(activeTrips(special,'2026-09-15').length,5,'Exceptions-only service is valid');
assert.equal(timeMinutes('25:10:00'),1510);
assert(Number.isNaN(timeMinutes('10:99:00')));
assert.equal(studyFreshness(data,'2026-09-14'),'current');
assert.equal(studyFreshness(data,'2026-10-15'),'review-due');
assert.equal(studyFreshness(data,'2027-04-01'),'expired');
assert.equal(data.groups.length,10);
assert.equal(new Set(data.groups.flatMap(g=>[g.outboundId,g.returnId])).size,17);
for (const row of pdf.rows) {
 const trip=data.trips.find(t=>t.direction===Number(row.direction)&&t.start===row.departure);
 const calls=row.direction==='0'?trip.stops:[...trip.stops].reverse();
 const actual=pdf.stopNames.map(name=>calls.find(s=>data.stops.find(p=>p.id===s.id).name===name).departure.slice(0,5));
 assert.deepEqual(actual,row.times);
}
const correction=data.trips.find(t=>t.direction===0&&t.start==='10:00').stops.find(s=>s.id==='7_01');
assert.equal(correction.sourceDeparture,'10:07:00');assert.equal(correction.departure,'10:08:00');
const origin=data.groups.find(g=>g.name==='光駅北口');
const conditions={earliest:540,walkingEachWay:10,shopping:45,boardingBuffer:10,returnBy:720,homeWalk:0};
const plans=shoppingPlans(data,'2026-09-15',origin,conditions);
assert.equal(plans.length,1);const p=plans[0];
assert.deepEqual([p.board.departure,p.arrive.arrival,p.returnBoard.departure,p.returnArrive.arrival],['10:08:00','10:19:00','11:40:00','11:51:00']);
assert.equal(p.extraMargin,6);assert.equal(p.boardingWait,16);
assert.equal(shoppingPlans(data,'2026-09-15',origin,{...conditions,shopping:52}).length,0,'Longer shop time misses the last return before noon');
assert.equal(shoppingPlans(data,'2026-09-15',origin,{...conditions,homeWalk:10}).length,0,'11:51 stop arrival does not mean home by noon');
assert.equal(shoppingPlans(data,'2026-09-15',origin,{...conditions,homeWalk:9}).length,1);
assert.equal(shoppingPlans(data,'2026-09-15',data.groups.at(-1),conditions).length,0,'No zero-length shopping trip');
assert.equal(shoppingPlans(data,'2027-04-01',origin,conditions).length,0);
assert.equal(shoppingPlans(data,'2026-09-15',origin,{...conditions,walkingEachWay:NaN}).length,0);
const oldDropoff=structuredClone(data);for(const t of oldDropoff.trips)for(const s of t.stops)if(s.id===origin.returnId)s.dropoff=1;
assert.equal(shoppingPlans(oldDropoff,'2026-09-15',origin,conditions).length,0,'Alighting restriction respected');
